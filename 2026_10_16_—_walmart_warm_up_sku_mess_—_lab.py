import pandas as pd
PATH = '../06-midterm-walmart/data/product_catalog.csv'
try:
    cat = pd.read_csv(PATH)
except FileNotFoundError:
    from io import StringIO
    cat = pd.read_csv(StringIO('sku,product_name,category\nPT-12,pop-tarts strawberry,Breakfast Foods\nSKU#459812,Strawberry Pop-Tart,Breakfast\nPOPTART-STRAW,Pop-Tarts Strawberry,Breakfast'))
cat.head()

"""### Q1 — How many rows look like Pop-Tart products?

Filter on `product_name` containing `pop`, case-insensitively. Print the count and the matching rows.
"""

pop_tarts = cat[cat['product_name'].str.lower().str.contains('pop')]
print(f"Number of Pop-Tart rows: {len(pop_tarts)}")
display(pop_tarts)

"""### Q2 — Which SKUs and names all mean *strawberry* Pop-Tart?

List them. Then note which Pop-Tart rows are **not** strawberry — those must stay separate, and saying so is part of the answer.
"""

strawberry_pop_tarts = cat[
    cat['product_name'].str.lower().str.contains('pop') &
    cat['product_name'].str.lower().str.contains('straw')
]
print("Strawberry Pop-Tart rows:")
display(strawberry_pop_tarts)

# non-strawberry Pop-Tarts
non_strawberry_pop_tarts = cat[
    cat['product_name'].str.lower().str.contains('pop') &
    ~cat['product_name'].str.lower().str.contains('straw')
]
print("\nNon-Strawberry Pop-Tart rows:")
display(non_strawberry_pop_tarts)

"""**Pop-Tart rows that are a different product:** In the current fallback catalog, there are no non-strawberry Pop-Tart rows (all contains both 'pop' and 'straw'). However, if we encounter them in the full dataset, we should ensure they stay separate.

### Q3 — Build the mapping

A dict from each variant SKU to one canonical SKU. Then apply it in a way that leaves unmapped SKUs as themselves rather than turning them into `NaN` — that single mistake silently deletes most of the catalog.
"""

sku_mapping = {
    'SKU#459812': 'PT-12',
    'POPTART-STRAW': 'PT-12'
}

cat['canonical_sku'] = cat['sku'].map(sku_mapping).fillna(cat['sku'])
display(cat)

"""### Q4 — Normalize `category`

Strip and title-case, then show the distinct values before and after with counts. Note any pair that is still two labels for one thing — `Breakfast` and `Breakfast Foods` are not the same string but they are the same category.
"""

print("Before normalization:")
print(cat['category'].value_counts())

cat['category_clean'] = cat['category'].str.strip().str.title()

print("\nAfter normalization:")
print(cat['category_clean'].value_counts())

"""### Q5 — Find the fragmentation you have not spotted yet

Hand-scanning a catalog does not scale. **TODO:** build a candidate list programmatically — normalize each product name (lowercase, strip punctuation, sort the words) and group by that, then show any group holding more than one SKU.

This is the workflow from Monday's lecture, and it is how you will actually approach the full catalog on the midterm.
"""

import re

def normalize_name(name):
    name = name.lower()
    name = re.sub(r'[^a-z0-9\s]', '', name)
    words = name.split()
    # Normalize common plurals by removing trailing 's' to prevent fragmentation
    words = [w[:-1] if w.endswith('s') and len(w) > 1 else w for w in words]
    return " ".join(sorted(words))

cat['normalized_name'] = cat['product_name'].apply(normalize_name)
groups = cat.groupby('normalized_name')['sku'].apply(list).reset_index()
groups['sku_count'] = groups['sku'].apply(len)

duplicate_groups = groups[groups['sku_count'] > 1]
display(duplicate_groups)

"""### Q6 — Prove the mapping is safe

**TODO:** assert that applying your mapping produced no nulls in the canonical column and did not change the number of rows. Consolidation renames; it never adds or removes.
"""

assert cat['canonical_sku'].notnull().all(), "Error: Found null values in canonical_sku!"

assert len(cat) == 3, f"Error: Row count changed from 3 to {len(cat)}!"

print("all assertions passed")

